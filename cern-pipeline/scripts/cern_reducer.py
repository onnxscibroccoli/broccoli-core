#!/usr/bin/env python3
"""
Linear-time statistical noise reducer.
Consumes flat JSON from harvest_github.py, clusters topics by simple keyword
frequency, computes Z-scores against a baseline, and emits a dense Markdown report.
"""

import json
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

RAW = Path("data/raw")
REPORT = Path("cern_signal_report.md")


def load_json(name: str) -> list:
    p = RAW / name
    if not p.exists():
        return []
    return json.loads(p.read_text())


def extract_topics(texts: list[str], min_len: int = 4) -> Counter:
    """Very lightweight topic extraction: word frequency after stopword filter."""
    stop = {
        "the", "a", "an", "and", "or", "for", "to", "in", "of", "on", "with",
        "is", "are", "was", "be", "this", "that", "it", "as", "by", "from",
        "add", "fix", "update", "bug", "issue", "pr", "pull", "request"
    }
    c = Counter()
    for t in texts:
        if not t:
            continue
        words = [w.lower() for w in t.split() if len(w) >= min_len and w.lower() not in stop]
        c.update(words)
    return c


def compute_z(freq: float, mean: float, std: float) -> float:
    if std == 0 or np.isnan(std):
        return 0.0
    return (freq - mean) / std


def main():
    print("Initializing CERN linear-time reduction...")

    issues = load_json("issues.json")
    prs = load_json("prs.json")
    repos = load_json("repos.json")

    # Combine titles for topic signal
    titles = [i.get("title", "") for i in issues] + [p.get("title", "") for p in prs]
    topic_counts = extract_topics(titles)

    if not topic_counts:
        report = "# CERN Ecosystem Signal Report\n\nNo issues or PRs found.\n"
        REPORT.write_text(report)
        print("Empty ecosystem – wrote empty report")
        return

    # Build DataFrame of top topics
    top = topic_counts.most_common(40)
    df = pd.DataFrame(top, columns=["topic", "mention_frequency"])

    # Baseline: use the distribution of all frequencies as empirical baseline
    # (In a real multi-week system you would load historical snapshots)
    freqs = df["mention_frequency"].astype(float)
    baseline_mean = float(freqs.mean())
    baseline_std = float(freqs.std(ddof=0)) if len(freqs) > 1 else 1.0

    df["baseline_mean"] = baseline_mean
    df["baseline_std"] = baseline_std
    df["sigma"] = df["mention_frequency"].apply(
        lambda f: compute_z(f, baseline_mean, baseline_std)
    )

    discoveries = df[df["sigma"] >= 2.0].sort_values("sigma", ascending=False)

    # Build report
    lines = [
        "# CERN Ecosystem Signal Report",
        "",
        "Generated by GitHub Actions linear-time reduction pipeline.",
        f"Repos scanned: {len(repos)} | Issues: {len(issues)} | PRs: {len(prs)}",
        "",
        "## Statistically Elevated Topics (≥ 2.0σ)",
        "",
        "| Topic | Frequency | Baseline μ | σ | Status |",
        "| :--- | ---: | ---: | ---: | :--- |",
    ]

    for _, row in discoveries.iterrows():
        sig = row["sigma"]
        status = "DISCOVERY (5σ+)" if sig >= 5 else ("EVIDENCE (3σ+)" if sig >= 3 else "ELEVATED")
        lines.append(
            f"| **{row['topic']}** | {int(row['mention_frequency'])} | "
            f"{baseline_mean:.1f} | **{sig:.2f}σ** | {status} |"
        )

    if discoveries.empty:
        lines.append("| (none above threshold) | – | – | – | – |")

    lines.extend([
        "",
        "## Raw Top 15 (unfiltered)",
        "",
        "| Rank | Topic | Count |",
        "| ---: | :--- | ---: |",
    ])
    for i, (topic, cnt) in enumerate(top[:15], 1):
        lines.append(f"| {i} | {topic} | {cnt} |")

    lines.append("")
    lines.append("---")
    lines.append("*Only the report (not raw JSON) should be ingested by an LLM.*")

    REPORT.write_text("\n".join(lines))
    print(f"Reduction complete → {REPORT}")


if __name__ == "__main__":
    main()
